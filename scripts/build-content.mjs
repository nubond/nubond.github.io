// Collects everything under content/ into src/generated/content.ts:
//   content/<page>/<name>/        -> live example (all files of the folder, entry point index.ts)
//   content/<page>/<name>.<ext>   -> static snippet
// Example TypeScript is precompiled here with the same options the browser uses after an edit,
// so the first render of every example needs no compiler download.
//
//   node scripts/build-content.mjs                    generate once (fails on errors)
//   node scripts/build-content.mjs --watch -- parcel  generate, then regenerate on every content change
//                                                     while running the command after '--'
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync, watch } from 'node:fs';
import { spawn } from 'node:child_process';
import { join, extname, basename, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contentRoot = join(root, 'content');
const output = join(root, 'src', 'generated', 'content.ts');

const compilerOptions = JSON.parse(readFileSync(join(contentRoot, 'compiler-options.json'), 'utf8'));

const LANGUAGES = { '.ts': 'ts', '.js': 'ts', '.html': 'html', '.css': 'css', '.json': 'json', '.sh': 'sh', '.txt': 'txt' };

const fileOrder = name => {
    // index.ts, index.html first, then the rest grouped by base name (ts, html, css)
    const base = basename(name, extname(name));
    const extensionRank = { '.ts': 0, '.html': 1, '.css': 2 }[extname(name)] ?? 3;
    return `${base === 'index' ? 0 : 1}|${base}|${extensionRank}`;
};

const read = path => readFileSync(path, 'utf8').replace(/\r\n/g, '\n').replace(/\s+$/, '') + '\n';

function generate() {
    const examples = {};
    const snippets = {};
    const errors = [];

    for (const page of readdirSync(contentRoot).sort()) {
        const pagePath = join(contentRoot, page);
        if (!statSync(pagePath).isDirectory()) {
            continue;
        }

        for (const entry of readdirSync(pagePath).sort()) {
            const entryPath = join(pagePath, entry);

            if (statSync(entryPath).isDirectory()) {
                const id = `${page}/${entry}`;
                const files = readdirSync(entryPath)
                    .filter(name => LANGUAGES[extname(name)] !== undefined)
                    .sort((a, b) => fileOrder(a).localeCompare(fileOrder(b)))
                    .map(name => ({ name, lang: LANGUAGES[extname(name)], code: read(join(entryPath, name)) }));

                if (!files.some(file => file.name === 'index.ts')) {
                    errors.push(`${id}: live example has no index.ts`);
                    continue;
                }

                const compiled = {};
                for (const file of files.filter(file => file.lang === 'ts')) {
                    const result = ts.transpileModule(file.code, { compilerOptions, fileName: file.name, reportDiagnostics: true });
                    for (const diagnostic of result.diagnostics ?? []) {
                        errors.push(`${id}/${file.name}: ${ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n')}`);
                    }
                    compiled[file.name] = result.outputText;
                }

                examples[id] = { files, compiled };
            } else {
                const extension = extname(entry);
                snippets[`${page}/${entry}`] = { lang: LANGUAGES[extension] ?? 'txt', code: read(entryPath) };
            }
        }
    }

    if (errors.length > 0) {
        console.error(errors.join('\n'));
        return false;
    }

    mkdirSync(dirname(output), { recursive: true });
    const generated =
`// GENERATED by scripts/build-content.mjs from content/ - do not edit
import { IExampleData, ISnippetData } from '../shared/models/content';

export const EXAMPLES: { [id: string]: IExampleData } = ${JSON.stringify(examples, null, 1)};

export const SNIPPETS: { [id: string]: ISnippetData } = ${JSON.stringify(snippets, null, 1)};
`;

    // an unchanged file is not rewritten, so the dev server does not rebuild for nothing
    let current;
    try {
        current = readFileSync(output, 'utf8');
    } catch {
        current = undefined;
    }
    if (current !== generated) {
        writeFileSync(output, generated);
    }

    console.log(`content: ${Object.keys(examples).length} examples, ${Object.keys(snippets).length} snippets`);
    return true;
}

const watchMode = process.argv.includes('--watch');
const commandIndex = process.argv.indexOf('--');

if (!generate() && !watchMode) {
    process.exit(1);
}

if (watchMode) {
    let timer;
    watch(contentRoot, { recursive: true }, () => {
        clearTimeout(timer);
        timer = setTimeout(() => {
            try {
                generate();
            } catch (ex) {
                console.error(ex);
            }
        }, 150);
    });

    if (commandIndex > 0) {
        const child = spawn(process.argv.slice(commandIndex + 1).join(' '), { shell: true, stdio: 'inherit' });
        child.on('exit', code => process.exit(code ?? 0));
    }
}
